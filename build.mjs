// Build: tạo tokens màu M3 (từ seed), bundle JS bằng esbuild, ghi ra thư mục gốc để "Load unpacked" trực tiếp.
import { build } from 'esbuild';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

// material-color-utilities dùng import không đuôi .js nên Node ESM không nạp trực tiếp được -> bundle tạm.
await build({
  stdin: { contents: "export * from '@material/material-color-utilities';", resolveDir: process.cwd() },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: '.cache/mcu.mjs',
  logLevel: 'error',
});
const { argbFromHex, themeFromSourceColor, hexFromArgb } = await import(pathToFileURL('.cache/mcu.mjs').href);

const SEED = '#5B6CF0';

// ---- 1) Màu Material 3 (light + dark) ----
const theme = themeFromSourceColor(argbFromHex(SEED));
const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());

function tokens(scheme, dark) {
  const out = {};
  for (const [k, v] of Object.entries(scheme.toJSON())) out[`--md-sys-color-${kebab(k)}`] = hexFromArgb(v);
  const n = theme.palettes.neutral;
  const tiers = dark
    ? { 'surface-container-lowest': 4, 'surface-container-low': 10, 'surface-container': 12, 'surface-container-high': 17, 'surface-container-highest': 22, 'surface-dim': 6, 'surface-bright': 24 }
    : { 'surface-container-lowest': 100, 'surface-container-low': 96, 'surface-container': 94, 'surface-container-high': 92, 'surface-container-highest': 90, 'surface-dim': 87, 'surface-bright': 98 };
  for (const [k, tone] of Object.entries(tiers)) out[`--md-sys-color-${k}`] = hexFromArgb(n.tone(tone));
  return Object.entries(out).map(([k, v]) => `  ${k}: ${v};`).join('\n');
}

const tokenCss =
  `/* Generated by build.mjs — seed ${SEED} */\n` +
  `:root {\n${tokens(theme.schemes.light, false)}\n}\n` +
  `@media (prefers-color-scheme: dark) {\n  :root {\n${tokens(theme.schemes.dark, true).replace(/^/gm, '  ')}\n  }\n}\n\n`;

fs.writeFileSync('app.css', tokenCss + fs.readFileSync('src/app.css', 'utf8'));
fs.copyFileSync('src/app.html', 'app.html');

// ---- 2) JS ----
const common = { bundle: true, minify: true, target: 'chrome116', logLevel: 'info', legalComments: 'none' };

await build({ ...common, entryPoints: { app: 'src/app.js' }, outdir: '.', format: 'esm' });
await build({ ...common, entryPoints: { background: 'src/background.js' }, outdir: '.', format: 'esm' });
await build({
  ...common,
  entryPoints: { content: 'src/content.js' },
  outdir: '.',
  format: 'iife',
  loader: { '.css': 'text' },
});

console.log('Build OK');
